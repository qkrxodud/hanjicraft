// i18n functionality
class I18n {
    constructor() {
        this.currentLang = localStorage.getItem('language') || 'ko';
        this.translations = translations;
    }

    t(key) {
        const keys = key.split('.');
        let value = this.translations[this.currentLang];

        for (const k of keys) {
            if (value && typeof value === 'object') {
                value = value[k];
            } else {
                return key; // Return key if translation not found
            }
        }

        return value || key;
    }

    setLanguage(lang) {
        if (this.translations[lang]) {
            this.currentLang = lang;
            localStorage.setItem('language', lang);
            this.updateUI();
        }
    }

    getCurrentLanguage() {
        return this.currentLang;
    }

    updateUI() {
        // Update all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            const translation = this.t(key);

            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translation;
            } else {
                element.textContent = translation;
            }
        });

        // Update HTML lang attribute
        document.documentElement.lang = this.currentLang;

        // Update page title if needed
        if (document.querySelector('[data-i18n-title]')) {
            const titleKey = document.querySelector('[data-i18n-title]').getAttribute('data-i18n-title');
            document.title = this.t(titleKey);
        }

        // Trigger custom event for other components to listen
        window.dispatchEvent(new CustomEvent('languageChanged', {
            detail: { language: this.currentLang }
        }));
    }

    getSupportedLanguages() {
        return Object.keys(this.translations);
    }
}

// Global i18n instance
window.i18n = new I18n();

// Export for module use if needed
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { I18n, translations };
}